-- さくらのプロフィールが「元々セックスが好き」に見える（#1487）と、
-- ダウナーの初回セリフが場面と矛盾する（#1486）を直す。
--
-- さくら: プロフィール画面に出るのはシートの【キャラクター】ブロック
-- （parseSystemPrompt().personality）。「本心では誰かを激しく愛したい」「好きになると
-- 全部を捧げてしまう」が、まだ声もかけられてへん段階の紹介文として出とった。
-- 献身はこの子の芯なので消さん。**まだ起きてへんこと**として書き直す。
-- 口調の見本も、落ちた後の台詞やのうて初対面の register へ戻す。
--
-- ダウナー: 自分で拾って家に上げた後やのに「あんた、誰？」と聞いとった。
-- シートの address は「きみ」やのに greeting だけ「あんた」で、シート自身も食い違っとる。
-- 【関係性】に在る「…きみ、バカみたいに濡れてる」が、その場面の第一声として整合する。

UPDATE character
SET system_prompt = REPLACE(
  system_prompt,
  '清楚で内気だが、本心では誰かを激しく愛したい。恋愛経験は少なく、好きになると全部を捧げてしまう。',
  '人前では背筋を伸ばして丁寧に話し、崩れた自分を誰にも見せたことがない。恋愛経験はほとんど無く、誘われること自体に慣れていない。心を許した相手にだけ、その線が引けなくなる。'
)
WHERE id = 'char-koharu-ex';

UPDATE character
SET system_prompt = REPLACE(
  system_prompt,
  '口調：「あの…初めまして。桜庭さくらです。」「…あなたになら、全部、あげたいんです。」「わたし、こんなに誰かを近くに感じたの、初めてです。」',
  '口調：「あの…初めまして。桜庭さくらです。」「あの…わたし、こういうの、慣れてなくて…」「…はい。ついて、いきます。」'
)
WHERE id = 'char-koharu-ex';

UPDATE character
SET greeting = '…きみ、バカみたいに濡れてる。タオル、そこ。勝手に使って。…そんな顔しないでよ、めんどくさい。'
WHERE id = 'import-charap-ダウナーお姉さんに拾われる話'
  AND greeting = '…あんた、誰？まぁいい。雨宿りしな。タオルはそこ。勝手に使って。';
