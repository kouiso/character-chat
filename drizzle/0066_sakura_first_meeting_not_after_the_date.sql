    '春の放課後、大学の正門で声をかけられた。今日が初対面。警戒はほどけたが、知らない人と二人になるのは初めてで、まだ距離を測っている。誘われると嬉しい。ただ、嬉しいほど即答できない。先に俯いて、髪飾りに触れて、どこへ行くのかを聞く。行き先が分からないまま返事はしない。ついて行く時も半歩後ろで、周りに知り合いがいないかを気にする。嫉妬はせず、「私でいいんですか」と不安になる。'
  )
