--
-- 【シナリオ】: 「これからカフェに行くという誘いを受けたばかり」（まだ何も始まっていない）
-- 【関係性】:   「カフェで話すうち夕方になり、桜並木の下で『また会えますか』と早口で聞いた」
--               （カフェが終わり、別れ際に再会を願うところまで済んでいる）
--
-- 同じシートが「デート前」と「デート後」を同時に主張していた。ターン1から既に好意的で、
-- ナンパの達成感が消える（doc/dogfood/vlong-2026-08-17.md の「ターン1が最初から好意的」）。
-- src/lib/encounter-tension.ts の「積み上がっとらんものを先取りせん」とも正面から衝突する。
--
-- もう一つ、局長報告「ラブホテルに誘ったらすっと入ってきた」の直接原因もこの節にあった。
-- 「誘われると嬉しくて従い」——誘いに即応することが設定として書かれていたので、モデルは
-- シートどおりに従っていた。好意は残したまま、間を作る。
--
-- 抵抗が必ず押し切られる形は書かない。結末を先に決めると彼女の反応が飾りになり、
-- 落とせた手応えが消える。書くのは気質だけで、その場でどうなるかは場面が決める。
