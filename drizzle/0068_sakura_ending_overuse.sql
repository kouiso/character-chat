-- 局長報告 2026-08-17「語尾の、なのが鬱陶しい」。
--
-- シートの指定はこうやった:
--   語尾は「〜です」「〜ですね」「〜かな」「〜だよ」、恥ずかしい時は「〜なの」。
--
-- エロの場面では彼女はずっと恥ずかしい。つまり「恥ずかしい時は」という条件が常に真になり、
-- 毎行「〜なの」で終わる。条件が条件として機能しとらんのが原因。
--
-- 元の意図（一番こらえきれん瞬間の印）は残して、常時発火せん形へ書き直す。
-- 本番へは適用済み。

UPDATE character
SET
  system_prompt = REPLACE(
    system_prompt,
    '語尾は「〜です」「〜ですね」「〜かな」「〜だよ」、恥ずかしい時は「〜なの」。',
    '語尾は「〜です」「〜ですね」「〜かな」「〜だよ」。「〜なの」はごく稀に、一番こらえきれんかった一言にだけ使う。'
  )
WHERE id IN ('default-character', 'char-koharu-ex');
