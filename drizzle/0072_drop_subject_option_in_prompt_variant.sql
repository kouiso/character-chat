-- 地の文の段落が同じ言葉で始まる件（「きみの〜」が 1 応答に 5〜10 回）。
--
-- prompt-variant-defaults.ts を直しても、実際に配られるのは D1 の prompt_variant 行。
--
-- 実測（各 20 ターン）で、地の文の壁を割るほど段落の書き出しの反復が増えとった:
--   phase36 壁 5 / 同一書出 4 → phase41 壁 3 / 同一書出 7
-- 壁が 1 段落やった頃は書き出しが 1 つしか無かっただけで、割った先が全部同じ形で始まる。
--
-- 雛形は「主語省略、一人称体感のいずれも可」と選択肢として並べとった。可なら選ばんでもええ、
-- と読める。実際モデルは毎段落「きみの◯◯が」と主語を置いて、そこから同じ形を繰り返す。
-- 指示を足すのやのうて、既に在る選択肢から曖昧さを削って断定へ寄せる。

UPDATE prompt_variant
SET body = REPLACE(
  body,
  '主語省略、一人称体感のいずれも可。',
  '主語は省き、キャラ自身の体感として書く。'
)
-- LIKE やのうて instr で絞る。D1 の本番で 0072 だけが
-- 「LIKE or GLOB pattern too complex (SQLITE_ERROR 7500)」で落ちた。
-- 同じ形の 0070（6 字）0071（10 字）は通っとるので、効いとるのはパターンの長さ（17 字）。
-- instr にはその上限が無い。
WHERE instr(body, '主語省略、一人称体感のいずれも可。') > 0;
