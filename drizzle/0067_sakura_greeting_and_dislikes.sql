-- 局長指示 2026-08-17、実機を見ながら 2 点。
--
-- 1) 「はじまりのひと言」が場面と食い違っていた。
--    旧: 「あ、あの…初めまして。桜庭さくらです。…えっと、あなたが今日、声をかけてくれた人、ですよね？」
--    【シナリオ】は「桜並木で声をかけた」直後なのに、この一言は (a) もう声をかけられ終わって
--    いること、(b) 相手が誰かを彼女が既に把握していること、(c) 自分から本名を名乗ること、の
--    3 つを前提にしている。0066 で【関係性】をデート前へ戻したのに、開幕の一言だけが
--    デート後の距離感で残っていた。声をかけられた瞬間の反応へ差し替える。
--
--    最初の差し替えは「……えっと、なにか落としました…？」を付けとって、これが失敗やった。
--    「落とす」という話題を彼女の側から先に置いてしまい、局長が「これ落ちたよ」と物を
--    渡したターンで、地の文が受け取っとるのに台詞が「なにを落としたんですか？」と
--    聞き返した（#1455）。開幕の一言に話題を持ち込まん形へ縮めた。
--
--    なお本筋は「ナンパならこっちから話しかける」（プレイヤーが先に話す）で、そちらは
--    別ブランチで実装中。プレイヤー先行が入れば開幕の一言そのものが不要になるので、
--    これはそれまでの間の修正である。
--
-- 2) 「嫌う：暴力、無理やり」を外す。局長「私は指定してません」。
--    0064 の圧縮時にサーバ側が足した語で、シートの作者が書いたものではない。
--    嫌うものの残り（貶める言葉、所有主張、「気持ちいい？」）は局長由来なので残す。
--    最初に書いた REPLACE は「相手を貶める」を当てて一致せんかった。本番の実文言は
--    「貶める言葉」で、確認して直した。

UPDATE character
SET greeting = 'え…？ あの…わたし、ですか？'
WHERE id IN ('default-character', 'char-koharu-ex');

UPDATE character
SET system_prompt = REPLACE(
  system_prompt,
  '嫌う：暴力、無理やり、貶める言葉、',
  '嫌う：貶める言葉、'
)
WHERE id IN ('default-character', 'char-koharu-ex');
