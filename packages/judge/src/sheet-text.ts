// キャラシートの改行を直す。D1 に入っとるシートには、改行が本物の改行やのうて
// 「\」と「n」の2文字で保存されとる物がある（本番221体のうち64体。refute-r4 2026-09-14 #5）。
//
// これを畳まんと、行頭・行末に固定したパターンが全部「1行しか無い」と読んでまう。
// forbidden_words 行も、口調欄も、敬語の指示も、丸ごと見えんくなる——落ちるべき語が
// 落ちんのに、エラーも出ん形で静かに効かんくなる。
//
// 直す場所は読み込み側やのうてパーサ側。テストの都合で本番データを整形するだけやと、
// v2 の実行時に D1 から同じ形を読んだ時にまた同じ穴が開く。シートを解釈する側が
// この書き方に耐えるのが本筋なので、シートを読む入口では必ずここを通す。
export const normalizeSheetText = (sheet: string): string => sheet.replace(/\\r\\n|\\n/gu, "\n");
